export function modulesByDomain(domain: ModuleDomain): ModuleEntry[] {
  return MODULES.filter((m) => m.domain === domain);
}

export function moduleBySlug(slug: string): ModuleEntry | undefined {
  return MODULES.find(
    (m) =>
      m.slug === slug ||
      m.slugEn === slug ||
      m.slugFr === slug ||
      m.slugPt === slug ||
      m.slugDe === slug ||
      m.slugIt === slug ||
      m.slugPl === slug ||
      m.slugPtBr === slug ||
      m.slugEsMx === slug
  );
}

export function moduleSlug(mod: ModuleEntry, locale: Locale): string {
  if (locale === 'pt-br') return mod.slugPtBr ?? mod.slugPt ?? mod.slug;
  if (locale === 'es-mx') return mod.slugEsMx ?? mod.slug;
  if (locale === 'en') return mod.slugEn ?? mod.slug;
  if (locale === 'fr') return mod.slugFr ?? mod.slug;
  if (locale === 'pt') return mod.slugPt ?? mod.slug;
  if (locale === 'de') return mod.slugDe ?? mod.slug;
  if (locale === 'it') return mod.slugIt ?? mod.slug;
  if (locale === 'pl') return mod.slugPl ?? mod.slug;
  return mod.slug;
}

